//! T2 — worked examples for the manual, produced by running the commands.
//!
//! # Why generated
//!
//! `Documentation/CLI.md` documents 28 items and, until 1.2.0, showed almost no
//! complete invocation. It answers *what does this field mean* for a reader who
//! already knows what to type; it did not answer *what does this look like*.
//!
//! The obvious fix is to paste some output into the manual. This repository has
//! learned what that costs twice in one year: `D-A16` sat recorded and unapplied
//! in the normative specification for two releases, and the `NASA_FACT_SHEET`
//! citation pointed at a URL that had stopped resolving. Both were copies, and
//! both drifted silently because nothing compared them with the thing they
//! described.
//!
//! So the examples are generated by **executing the commands** and capturing
//! what they print, and `check-docs` fails if the committed file is not what a
//! fresh run produces. An example cannot show output the program does not
//! produce, and a change in output is a failing build rather than a
//! documentation bug nobody notices.
//!
//! # Why a separate file
//!
//! `CLI-EXAMPLES.md` rather than injection into `CLI.md`, because a generator
//! that rewrites a hand-written file in place has to be trusted with the
//! hand-written parts. `CLI.md` links to it. The generated file says at the top
//! that it is generated, since a reader who edits it will otherwise lose the
//! edit at the next `gen-examples`.
//!
//! # What is deliberately not here
//!
//! `now` and `tour`'s clock-dependent output. `now` reads the system clock, so
//! its output differs on every run and could never match a committed file; the
//! manual documents it and the examples skip it, which is stated in the file
//! rather than left as an unexplained absence.

