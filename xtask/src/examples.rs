/// Run one example against the built binary and return its output.
fn capture(bin: &Path, args: &[&str]) -> Result<String, String> {
    // `wallclock` needs the non-default `tui` feature. A binary without it
    // rejects the subcommand, and the resulting file would silently document a
    // program that is missing a command — so this is an error and names the fix.
    let out = Command::new(bin)
        .args(args)
        .env("NO_COLOR", "1")
        // A fixed width, so the committed file does not depend on the terminal
        // that generated it.
        .env("COLUMNS", "80")
        .output()
        .map_err(|e| format!("{}: {e}", bin.display()))?;
    let mut text = String::from_utf8_lossy(&out.stdout).into_owned();
    let err = String::from_utf8_lossy(&out.stderr);
    if err.contains("unrecognized subcommand") || err.contains("unexpected argument") {
        return Err(format!(
            "`ucal {}` was rejected by the binary: it is probably built without \
             `--features tui`. Run `cargo build --release -p ucal --features tui`.",
            args.join(" ")
        ));
    }
    if !err.trim().is_empty() {
        text.push_str(err.trim_end());
        text.push('\n');
    }
    Ok(text)
}

/// Build the examples document.
pub fn generate(root: &Path, bin: &Path) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("# Worked examples\n\n");
    out.push_str("**Generated — do not edit.** Every block below is the real output of the command above it, captured by running it. Regenerate with:\n\n");
    out.push_str("```\ncargo build --release -p ucal --features tui\ncargo run -p xtask -- gen-examples\n```\n\n");
    out.push_str("`cargo run -p xtask -- check-docs` fails if this file is not what a fresh run produces, so an example cannot describe output the program does not produce. Field-by-field documentation is in [`CLI.md`](CLI.md).\n\n");
    out.push_str("`ucal now` and `ucal tour` are absent on purpose: `now` reads the system clock, so its output differs on every run and could never match a committed file.\n\n");
    out.push_str("Colour is off and the width is 80 columns, so these match a redirected run rather than a terminal.\n\n---\n");

    for ex in examples() {
        let text = capture(bin, ex.args)?;
        out.push_str(&format!("\n## `ucal {}`\n\n{}\n\n```\n{}```\n", ex.args.join(" "), ex.why, text));
    }
    let _ = root;
    Ok(out)
}

fn path_of(root: &Path) -> std::path::PathBuf {
    root.join("Documentation/CLI-EXAMPLES.md")
}

/// The release binary, which must exist before the examples can be generated.
fn binary(root: &Path) -> Result<std::path::PathBuf, String> {
    let bin = root.join("target/release/ucal");
    if bin.exists() {
        Ok(bin)
    } else {
        Err(format!(
            "{} is missing; run `cargo build --release -p ucal --features tui` first",
            bin.display()
        ))
    }
}

/// Write the examples file.
pub fn write(root: &Path) -> Result<std::path::PathBuf, String> {
    let bin = binary(root)?;
    let text = generate(root, &bin)?;
    let path = path_of(root);
    std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(path)
}

/// Fail if the committed examples are not what a fresh run produces.
///
/// Skipped, with a message, when the release binary is absent: this check needs
/// a built program and `check-docs` must stay runnable on a clean checkout.
/// Saying so is the point — a check that silently passes when it cannot run is
/// how a stale file survives.
///
/// # It can fail for a reason that is not a defect
///
/// The binary it runs is whatever is at `target/release/ucal`, and nothing here
/// knows whether that is current. A tree whose sources have moved since the last
/// `cargo build --release` produces a **false failure**: the committed file is
/// correct and the binary is old.
///
/// That happened during 1.4.0 and cost a few minutes of looking for a defect
/// that was not there. CI never sees it — every run builds from scratch — so
/// this is a local-only trap, and the failure message names the fix rather than
/// the diagnosis, which is why it reads as worse than it is.
///
/// Not solved by having this build the binary: `check-docs` would then take
/// minutes instead of milliseconds, and a check nobody runs because it is slow
/// is worse than one that occasionally misreports. Recorded instead, and the
/// release procedure builds first.
pub fn check(root: &Path) -> Result<Option<usize>, String> {
    let Ok(bin) = binary(root) else {
        return Ok(None);
    };
    let want = generate(root, &bin)?;
    let path = path_of(root);
    let have = std::fs::read_to_string(&path)
        .map_err(|_| format!("{} is missing; run `cargo run -p xtask -- gen-examples`", path.display()))?;
    if have == want {
        Ok(Some(examples().len()))
    } else {
        Err(format!(
            "{} does not match what target/release/ucal produces.\n          \
             If sources changed since the last release build, that binary is \
             stale and this is a false alarm: `cargo build --release -p ucal` \
             first.\n          Otherwise: `cargo run -p xtask -- gen-examples`",
            path.display()
        ))
    }
}
